"""
test_run.py — Offline & live verification CLI

Usage:
  python test_run.py --mock
      Run end-to-end tests with synthetic data. Zero API keys needed.
      Verifies math logic, journal, and console notifier.

  python test_run.py --mock --send-telegram
      Like --mock, but sends a REAL Telegram card with [✅ Accept & Enter] /
      [❌ Decline] buttons if TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID are
      set in .env. Requires no listen loop — just sends the card.

  python test_run.py --mock --send-telegram --listen
      Sends the Telegram card AND starts the interactive listener loop for
      30 seconds so you can tap the button on your phone and verify the
      full execution flow (MockDemoExecutor will simulate the fill).

  python test_run.py --mock --regime uptrend|downtrend|ranging
      Test a specific price regime.

  python test_run.py --live
      Fetch real EUR/USD data from Twelve Data and run full Gate 2 + Gate 3.
      Requires TWELVE_DATA_API_KEY and GEMINI_API_KEY in .env.
"""

import argparse
import json
import os
import sys

import config


# ─────────────────────────────────────────────────────────────────────────────
# Test helpers
# ─────────────────────────────────────────────────────────────────────────────

def _header(title: str) -> None:
    print(f"\n{'━'*55}")
    print(f"  {title}")
    print(f"{'━'*55}")


def _ok(label: str, value: str = "") -> None:
    print(f"  ✅ {label} {value}")


def _fail(label: str, detail: str = "") -> None:
    print(f"  ❌ FAIL: {label} {detail}")
    sys.exit(1)


def _check(condition: bool, label: str, detail: str = "") -> None:
    if condition:
        _ok(label, detail)
    else:
        _fail(label, detail)


# ─────────────────────────────────────────────────────────────────────────────
# Synthetic "approved" signal builder (for the interactive Telegram test)
# ─────────────────────────────────────────────────────────────────────────────

def _build_mock_approved_signal(math_result: dict, regime: str) -> tuple[dict, dict]:
    """
    Build a mock math_result and ai_result that always looks like an ENTER_LONG
    so the Telegram card always shows the Accept / Decline buttons in --mock mode.

    For RANGING regime (which always fails Gate 2), we still synthesise a fake
    passing ai_result for UI testing purposes — clearly labelled [DEMO].
    """
    direction   = "ENTER_LONG" if regime != "downtrend" else "ENTER_SHORT"
    entry       = round(math_result.get("current_price", 1.08500), 5)
    stop_loss   = round(entry - 20 * 0.0001, 5)       # 20 pips SL
    take_profit = round(entry + 45 * 0.0001, 5)       # 45 pips TP  → ~2.25 R:R
    risk_usd    = round(config.ACCOUNT_BALANCE * config.MAX_RISK_PERCENT, 2)
    # Minimum 0.01 std lots for the demo
    std_lots    = max(round(
        risk_usd / ((20 * config.ACCOUNT_BALANCE * config.MAX_RISK_PERCENT) * 10), 2
    ), 0.01)

    # Patch math_result fields so notifier._build_signal() picks up real lots/units
    mock_math = dict(math_result)
    mock_math.update({
        "direction":                direction,
        "entry_price":              entry,
        "stop_loss":                stop_loss,
        "take_profit":              take_profit,
        "risk_reward_ratio":        2.25,
        "position_size_lots":       std_lots,
        "position_size_micro_lots": round(std_lots * 100, 2),
        "position_size_units":      int(std_lots * 100_000),
        "passed_math_gate":         True,
        "fail_reasons":             [],
    })

    mock_ai = {
        "decision":          direction,
        "confluence_score":  85,
        "trend_1h":          math_result.get("trend_1h", "UPTREND"),
        "plain_english_summary": (
            "[DEMO TEST SIGNAL — not a real trade recommendation] "
            f"This is a synthetic {direction} setup generated by --mock mode to "
            "verify the full Telegram interactive approval workflow."
        ),
        "trade_plan": {
            "direction":   direction,
            "entry":       entry,
            "stop_loss":   stop_loss,
            "take_profit": take_profit,
            "risk_reward": 2.25,
            "risk_usd":    risk_usd,
            "lots":        std_lots,
        },
        "checklist_audit": {
            "step1_trend":      {"result": "PASS", "reasoning": "Mock 1H trend aligned."},
            "step2_zone_fib":   {"result": "PASS", "reasoning": "Mock S/R zone test."},
            "step3_candle":     {"result": "PASS", "reasoning": "Mock 15m candle trigger."},
            "step4_math":       {"result": "PASS", "reasoning": "Mock R:R 2.25 >= 2.0."},
            "step5_volatility": {"result": "PASS", "reasoning": "Mock ATR within normal range."},
        },
        "devils_advocate_risks": [
            "DEMO SIGNAL: This is a test; there is no real market edge here.",
            "Price may gap against the position on real market open.",
        ],
    }
    return mock_math, mock_ai


# ─────────────────────────────────────────────────────────────────────────────
# --mock mode
# ─────────────────────────────────────────────────────────────────────────────

def run_mock_tests(
    regime: str = "uptrend",
    send_telegram: bool = False,
    listen_seconds: int | None = None,
) -> None:
    """Full end-to-end test with synthetic data. No API keys required."""
    _header(f"🧪 MOCK TEST RUN — regime: {regime.upper()}")

    # ── Test imports ──────────────────────────────────────────────────────────
    print("\n[1/7] Testing imports …")
    try:
        import data_fetcher
        import market_math
        import ai_auditor
        import notifier as _notifier
        import journal
        import broker_executor
        import telegram_listener
        _ok("All modules imported successfully.")
    except ImportError as exc:
        _fail("Import error", str(exc))

    # ── Test mock data generation ─────────────────────────────────────────────
    print("\n[2/7] Generating mock data …")
    df_1h, df_15m = data_fetcher.generate_mock_data(regime=regime, seed=42)
    _check(len(df_1h) == 100,  "df_1h has 100 rows",  str(len(df_1h)))
    _check(len(df_15m) == 50,  "df_15m has 50 rows",  str(len(df_15m)))
    _check(all(c in df_1h.columns for c in ["open", "high", "low", "close"]),
           "df_1h has correct columns")
    _check(df_1h["high"].ge(df_1h["low"]).all(),  "All 1H highs >= lows (valid OHLC)")
    _check(df_15m["high"].ge(df_15m["low"]).all(), "All 15m highs >= lows (valid OHLC)")
    print(f"     Price range 1H: {df_1h['close'].min():.5f} → {df_1h['close'].max():.5f}")

    # ── Test market math ──────────────────────────────────────────────────────
    print("\n[3/7] Running market_math.analyse() …")
    result = market_math.analyse("EUR/USD (MOCK)", df_1h, df_15m)

    _check("trend_1h" in result,          "trend_1h key present", f"→ {result['trend_1h']}")
    _check("sr_zones" in result,          "sr_zones computed")
    _check("candle_story" in result,      "candle_story computed")
    _check("atr_15m" in result,           "atr_15m computed",     f"→ {result.get('atr_15m')}")
    _check("current_price" in result,     "current_price present")
    _check("risk_reward_ratio" in result, "risk_reward_ratio computed",
           f"→ {result.get('risk_reward_ratio')}")
    _check("passed_math_gate" in result,  "passed_math_gate key present",
           f"→ {result['passed_math_gate']}")
    _check("last_10_candles_15m" in result, "last_10_candles_15m present",
           f"→ {len(result['last_10_candles_15m'])} candles")
    _check("position_size_lots" in result, "position_size_lots (std lots) present",
           f"→ {result.get('position_size_lots')} std lots")
    _check("position_size_micro_lots" in result, "position_size_micro_lots present",
           f"→ {result.get('position_size_micro_lots')} µlots")

    if regime == "ranging":
        _check(
            not result["passed_math_gate"],
            "RANGING regime correctly fails math gate",
        )

    for zone in result["sr_zones"]:
        _check(
            zone["touch_count"] >= 2,
            f"Zone at {zone['price']} has ≥2 touches",
            f"({zone['touch_count']})",
        )

    if config.USE_V2_INDICATORS:
        fib = result.get("fibonacci", {})
        _check("available" in fib, "Fibonacci field present")
        if fib.get("available"):
            _check(
                fib["golden_zone_low"] < fib["golden_zone_high"],
                "Fibonacci golden zone is well-ordered",
            )

    # ── Test candle analysis ───────────────────────────────────────────────────
    print("\n[4/7] Verifying 15m candle story …")
    story = result["candle_story"]
    _check(story.get("available", False), "Candle story is available")
    _check("pattern" in story,            "Pattern detected",  f"→ {story.get('pattern')}")
    _check("body_pct" in story,           "body_pct computed", f"→ {story.get('body_pct')}")

    # ── Test CSV logging ───────────────────────────────────────────────────────
    print("\n[5/7] Testing journal.log_setup() …")

    original_log = journal.LOG_FILE
    journal.LOG_FILE = "/tmp/test_trades_log.csv"

    fake_ai = {
        "decision":          "NO_TRADE",
        "confluence_score":  55,
        "trend_1h":          result["trend_1h"],
        "plain_english_summary": "Test run only.",
        "trade_plan":        {"entry": None, "stop_loss": None, "take_profit": None,
                              "risk_reward": None, "risk_usd": None, "lots": None},
        "devils_advocate_risks": ["Test risk 1", "Test risk 2"],
        "checklist_audit":   {},
    }

    journal.log_setup("EUR/USD", result, fake_ai, outcome="SKIPPED", notes="mock test")
    _check(os.path.exists(journal.LOG_FILE), "trades_log.csv created")

    limit_reached, loss_count = journal.check_daily_loss_limit()
    _check(isinstance(limit_reached, bool), "check_daily_loss_limit() returns bool",
           f"→ limit={limit_reached}, losses={loss_count}")

    on_cooldown, hrs_left = journal.check_pair_cooldown("EUR/USD", hours=4)
    _check(isinstance(on_cooldown, bool), "check_pair_cooldown() returns bool",
           f"→ cooldown={on_cooldown}, hrs_left={hrs_left}")

    os.remove(journal.LOG_FILE)
    journal.LOG_FILE = original_log

    # ── Test MockDemoExecutor ─────────────────────────────────────────────────
    print("\n[6/7] Testing MockDemoExecutor …")
    _check(config.DEMO_MODE, "DEMO_MODE is True (safe)")

    executor = broker_executor.get_executor()
    _check(isinstance(executor, broker_executor.MockDemoExecutor),
           "get_executor() returned MockDemoExecutor")

    mock_math, mock_ai = _build_mock_approved_signal(result, regime)
    test_signal  = _notifier._build_signal("EUR/USD (MOCK)", mock_math, mock_ai)
    exec_result  = executor.execute_bracket_order(test_signal)

    _check(exec_result["success"],    "MockDemoExecutor.execute_bracket_order() succeeded")
    _check(exec_result["executor"] == "mock", "Executor tagged as 'mock'")
    _check(exec_result["standard_lots"] >= 0.01, "Standard lots >= 0.01",
           f"→ {exec_result['standard_lots']}")

    # Clean up active_trades.json test entry
    if os.path.exists(broker_executor.ACTIVE_TRADES_FILE):
        with open(broker_executor.ACTIVE_TRADES_FILE, encoding="utf-8") as fh:
            trades = json.load(fh)
        trades.pop(test_signal["signal_id"], None)
        with open(broker_executor.ACTIVE_TRADES_FILE, "w", encoding="utf-8") as fh:
            json.dump(trades, fh, indent=2)

    # ── Test notifier (Telegram card with buttons / console fallback) ──────────
    print("\n[7/7] Testing notifier (interactive Telegram card) …")

    demo_math, demo_ai = _build_mock_approved_signal(result, regime)

    if send_telegram and config.TELEGRAM_BOT_TOKEN and config.TELEGRAM_CHAT_ID:
        print("  → Sending REAL Telegram card with [✅ Accept & Enter] / [❌ Decline] buttons …")
        _notifier.send_alert("EUR/USD (MOCK DEMO)", demo_math, demo_ai)
        _ok("Interactive Telegram card sent — check your phone!")

        # Retrieve the signal_id that was just saved
        store = _notifier._load_pending_signals()
        last_signal = None
        for sig in store.values():
            if sig.get("pair") == "EUR/USD (MOCK DEMO)":
                if last_signal is None or sig["timestamp_eat"] > last_signal["timestamp_eat"]:
                    last_signal = sig

        if last_signal:
            _ok("Signal saved to pending_signals.json",
                f"→ ID: {last_signal['signal_id'][:8]}…")

        if listen_seconds:
            print(
                f"\n  🎧 Starting Telegram listener for {listen_seconds}s …"
                f"\n     Tap a button on your phone now!\n"
            )
            telegram_listener.listen(timeout_seconds=listen_seconds)
    else:
        # No Telegram credentials → console fallback
        orig_token = config.TELEGRAM_BOT_TOKEN
        orig_chat  = config.TELEGRAM_CHAT_ID
        config.TELEGRAM_BOT_TOKEN = ""
        config.TELEGRAM_CHAT_ID   = ""

        _notifier.send_alert("EUR/USD (MOCK DEMO)", demo_math, demo_ai)

        config.TELEGRAM_BOT_TOKEN = orig_token
        config.TELEGRAM_CHAT_ID   = orig_chat
        _ok("Notifier printed interactive card to console (no Telegram keys set).")
        if send_telegram:
            print("  ℹ️  --send-telegram was requested but TELEGRAM_BOT_TOKEN / "
                  "TELEGRAM_CHAT_ID are not set in .env. Add them and retry.")

    # ── Summary ───────────────────────────────────────────────────────────────
    _header("✅ ALL MOCK TESTS PASSED")
    print(f"\n  Regime tested : {regime.upper()}")
    print(f"  Trend found   : {result['trend_1h']}")
    print(f"  S/R zones     : {len(result['sr_zones'])} cluster(s)")
    print(f"  Math gate     : {'PASS' if result['passed_math_gate'] else 'FAIL (expected for RANGING)'}")
    print(f"  R:R ratio     : {result.get('risk_reward_ratio', 'N/A')}")
    print(f"  Std Lots      : {result.get('position_size_lots', 'N/A')} (MT5)")
    print(f"  Micro Lots    : {result.get('position_size_micro_lots', 'N/A')} (ref)")
    print(f"\n  Full Gate 2 JSON output:")
    display = {k: v for k, v in result.items() if k != "last_10_candles_15m"}
    print(json.dumps(display, indent=2, default=str))
    print()


# ─────────────────────────────────────────────────────────────────────────────
# --live mode
# ─────────────────────────────────────────────────────────────────────────────

def run_live_test() -> None:
    """
    Fetch real EUR/USD data from Twelve Data and run Gate 2 + Gate 3.
    Requires TWELVE_DATA_API_KEY and GEMINI_API_KEY in .env.
    """
    _header("🌐 LIVE TEST RUN — EUR/USD")

    if not config.TWELVE_DATA_API_KEY:
        _fail("TWELVE_DATA_API_KEY not set",
              "Add it to .env or set as an environment variable.")

    # Gate 1
    print("\n[Gate 1] Fetching EUR/USD candles from Twelve Data …")
    import data_fetcher
    df_1h, df_15m = data_fetcher.fetch_pair_data("EUR/USD")
    _ok("1H candles",  f"→ {len(df_1h)} rows, latest: {df_1h.index[-1]}")
    _ok("15m candles", f"→ {len(df_15m)} rows, latest: {df_15m.index[-1]}")

    # Gate 2
    print("\n[Gate 2] Running market_math.analyse() …")
    import market_math
    result = market_math.analyse("EUR/USD", df_1h, df_15m)

    print(f"\n  Trend        : {result['trend_1h']}")
    print(f"  Current Price: {result['current_price']}")
    print(f"  EMA50 / EMA200: {result.get('ema50_1h')} / {result.get('ema200_1h')}")
    print(f"  EMA Signal    : {result.get('ema_signal')}")
    print(f"  ATR (15m)     : {result.get('atr_15m')}")
    print(f"  S/R Zones     : {len(result['sr_zones'])} cluster(s)")
    print(f"  Near Zone?    : {result.get('price_near_key_zone')}")
    print(f"  Candle Pattern: {result['candle_story'].get('pattern')}")
    print(f"  R:R Ratio     : {result.get('risk_reward_ratio')}")
    print(f"  Std Lots      : {result.get('position_size_lots')} (MT5)")
    print(f"  Micro Lots    : {result.get('position_size_micro_lots')} (ref)")
    print(f"  Math Gate     : {'✅ PASS' if result['passed_math_gate'] else '❌ FAIL'}")

    for reason in result.get("fail_reasons", []):
        print(f"    ↳ {reason}")

    print(f"\n  Full Gate 2 JSON (compare with TradingView):")
    display = {k: v for k, v in result.items() if k != "last_10_candles_15m"}
    print(json.dumps(display, indent=2, default=str))

    # Gate 3 (only if Gate 2 passes)
    if result["passed_math_gate"]:
        print(f"\n[Gate 3] Sending to Gemini AI auditor …")
        import ai_auditor
        ai_result = ai_auditor.audit(result)
        print(f"\n  AI Decision   : {ai_result.get('decision')}")
        print(f"  Confluence    : {ai_result.get('confluence_score')}/100")
        print(f"\n  Full Gate 3 JSON:")
        print(json.dumps(ai_result, indent=2, default=str))
    else:
        print(f"\n[Gate 3] Skipped — Gate 2 did not pass.")

    _header("✅ LIVE TEST COMPLETE")


# ─────────────────────────────────────────────────────────────────────────────
# Entry point
# ─────────────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="AI Forex Co-Pilot — Test Runner",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--mock", action="store_true", help="Run offline mock tests.")
    group.add_argument("--live", action="store_true", help="Run live EUR/USD test.")
    parser.add_argument(
        "--regime",
        choices=["uptrend", "downtrend", "ranging"],
        default="uptrend",
        help="Price regime for --mock mode (default: uptrend).",
    )
    parser.add_argument(
        "--send-telegram",
        action="store_true",
        help=(
            "In --mock mode: send a REAL Telegram card with interactive buttons "
            "if TELEGRAM_BOT_TOKEN and TELEGRAM_CHAT_ID are set."
        ),
    )
    parser.add_argument(
        "--listen",
        action="store_true",
        help=(
            "In --mock --send-telegram mode: start the Telegram listener for 30 "
            "seconds so you can tap the button on your phone to test execution."
        ),
    )
    args = parser.parse_args()

    if args.mock:
        listen_secs = 30 if (args.listen and args.send_telegram) else None
        run_mock_tests(
            regime=args.regime,
            send_telegram=args.send_telegram,
            listen_seconds=listen_secs,
        )
    elif args.live:
        run_live_test()


if __name__ == "__main__":
    main()
